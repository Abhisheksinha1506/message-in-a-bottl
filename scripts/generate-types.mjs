// Development alternative to the Supabase CLI's Docker-based type generator.
// Uses the same official postgres-meta introspection and TypeScript template.
// Install @supabase/postgres-meta separately; pass its absolute package path.
// Configure PGHOST/PGPORT/PGDATABASE/PGUSER through the environment.
import { pathToFileURL } from "node:url";
const root = process.argv[2];
if (!root) throw new Error("Pass the postgres-meta package directory.");
const { PostgresMeta } = await import(
  pathToFileURL(`${root}/dist/lib/index.js`).href
);
const { apply } = await import(
  pathToFileURL(`${root}/dist/server/templates/typescript.js`).href
);
const meta = new PostgresMeta({
  host: process.env.PGHOST,
  port: Number(process.env.PGPORT || 5432),
  database: process.env.PGDATABASE || "postgres",
  user: process.env.PGUSER,
  password: process.env.PGPASSWORD,
});
const scoped = { includedSchemas: ["public"], includeColumns: false };
try {
  const results = await Promise.all([
    meta.schemas.list(),
    meta.tables.list(scoped),
    meta.views.list(scoped),
    meta.materializedViews.list(scoped),
    meta.columns.list(scoped),
    meta.relationships.list(),
    meta.functions.list(scoped),
    meta.types.list({ includeArrayTypes: true, includeSystemSchemas: true }),
  ]);
  if (results.some((r) => r.error))
    throw new Error("Schema introspection failed.");
  const [
    schemas,
    tables,
    views,
    materializedViews,
    columns,
    relationships,
    functions,
    types,
  ] = results.map((r) => r.data);
  const generated = await apply({
    schemas: schemas.filter((s) => s.name === "public"),
    tables,
    views,
    materializedViews,
    columns,
    relationships,
    functions: functions.filter(
      (f) => !["trigger", "event_trigger"].includes(f.return_type),
    ),
    types: types.filter((t) => !t.name.startsWith("_")),
    arrayTypes: types.filter((t) => t.name.startsWith("_")),
    detectOneToOneRelationships: true,
  });
  process.stdout.write(
    "// Generated by Supabase postgres-meta from the applied initial migration.\n" +
      generated,
  );
} finally {
  await meta.end();
}
